export function getAIConfig(): AIConfig {
  const envProvider = (process.env.AI_PROVIDER || 'gemini').toLowerCase() as AIProviderName;
  const provider = SUPPORTED_PROVIDERS.includes(envProvider) ? envProvider : 'gemini';

  const defaultModel = provider === 'gemini' 
    ? (process.env.GEMINI_MODEL || 'gemini-3.8-flash')
    : (process.env.OPENAI_MODEL || 'gpt-4o-mini');

  const supportedList = SUPPORTED_MODELS[provider] || [];
  const model = supportedList.includes(defaultModel) ? defaultModel : supportedList[0];

  return {
    provider,
    model,
    temperature: 0.7,
    max_tokens: 600,
    timeout_ms: 15000,
    retry_count: 2,
    enabled: true,
    prompt_version: 'v1.0'
  };
}

export function isValidTone(tone: string): tone is AITone {
  return Object.prototype.hasOwnProperty.call(SUPPORTED_TONES, tone);
}

export function isValidLanguage(lang: string): lang is AILanguage {
  return Object.prototype.hasOwnProperty.call(SUPPORTED_LANGUAGES, lang);
}
