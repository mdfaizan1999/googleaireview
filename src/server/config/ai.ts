export type AITone = 'professional' | 'friendly' | 'empathetic' | 'concise';
export type AILanguage = 'en' | 'hi';
export type AIProviderName = 'gemini' | 'openai' | 'mock';

export interface AIConfig {
  provider: AIProviderName;
  model: string;
  temperature: number;
  max_tokens: number;
  timeout_ms: number;
  retry_count: number;
  enabled: boolean;
  prompt_version: string;
}

export const SUPPORTED_PROVIDERS: AIProviderName[] = ['gemini', 'openai', 'mock'];

export const SUPPORTED_MODELS: Record<AIProviderName, string[]> = {
  gemini: ['gemini-3.8-flash', 'gemini-3.1-flash-lite', 'gemini-3.1-pro-preview'],
  openai: ['gpt-4o-mini', 'gpt-4o', 'gpt-3.5-turbo'],
  mock: ['mock-reviewer-model']
};

export const SUPPORTED_TONES: Record<AITone, { name: string; instruction: string }> = {
  professional: {
    name: 'Professional',
    instruction: 'Write in a polite, respectful, and business-appropriate tone. Maintain a polished corporate demeanor with clear and courteous phrasing.'
  },
  friendly: {
    name: 'Friendly',
    instruction: 'Write in a warm, welcoming, and approachable tone. Show cheerful appreciation and authentic hospitality as if greeting a regular patron.'
  },
  empathetic: {
    name: 'Empathetic',
    instruction: 'Write with deep understanding, active listening, and sincere care. Acknowledge customer sentiment with validation, warmth, and reassurance.'
  },
  concise: {
    name: 'Concise',
    instruction: 'Keep the response extremely direct, crisp, and to the point (no more than 2-3 sentences). Eliminate filler words while remaining courteous.'
  }
};

export const SUPPORTED_LANGUAGES: Record<AILanguage, { name: string; instruction: string }> = {
  en: {
    name: 'English',
    instruction: 'Respond strictly in natural, grammatically correct English.'
  },
  hi: {
    name: 'Hindi',
    instruction: 'Respond strictly in polite, natural conversational Hindi (Devanagari script or standard Hindi, polite "Aap" respectful register).'
  }
};

